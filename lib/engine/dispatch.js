// Notification Dispatch Engine (Simulates Twilio & Resend)

export async function dispatchNotifications(analysis) {
  if (!analysis || !analysis.isHighConviction) {
    return { dispatched: false, reason: 'Signal not high conviction (>90%)' };
  }

  const { symbol, confidenceScore, signal, targetEntry, targetExit } = analysis;
  const fundamental = analysis.layers.fundamental;
  const technical = analysis.layers.technical;
  const macro = analysis.layers.macro;

  // 1. Format Twilio SMS Payload
  const smsPayload = `[${signal}] $${symbol} | Conf: ${confidenceScore}% | Price: ${fundamental.currentPrice?.toFixed(2)} vs IV: ${fundamental.intrinsicValue?.toFixed(2)} | Tech: ${technical.trigger} | Macro: ${macro.catalyst.split(':')[0]} | Entry: ${targetEntry} | Exit: ${targetExit}`;

  // 2. Format Resend Email Payload (HTML)
  const emailHtml = `
    <h2>SentinelInvest 24/7 Alert: ${symbol}</h2>
    <p>A High Conviction <strong>${signal}</strong> signal was generated with a confidence score of ${confidenceScore}%.</p>
    
    <h3>1. Fundamental Analysis</h3>
    <ul>
      <li>Intrinsic Value (DCF): ${fundamental.intrinsicValue?.toFixed(2)}</li>
      <li>Margin of Safety: ${fundamental.marginOfSafety?.toFixed(2)}%</li>
      <li>Debt/Equity: ${fundamental.debtToEquity?.toFixed(2)}</li>
      <li>FCF Yield: ${fundamental.fcfYield?.toFixed(2)}%</li>
    </ul>

    <h3>2. Technical Analysis</h3>
    <ul>
      <li>Trigger: ${technical.trigger}</li>
      <li>RSI (14): ${technical.rsi14?.toFixed(2)}</li>
      <li>MACD Bullish: ${technical.macd?.isBullish ? 'Yes' : 'No'}</li>
    </ul>

    <h3>3. Macroeconomic Overlay</h3>
    <p>${macro.catalyst}</p>

    <hr/>
    <p><strong>Target Entry:</strong> ${targetEntry} | <strong>Target Exit:</strong> ${targetExit}</p>
    <p><em>Generated by SentinelInvest Autonomous Hub</em></p>
  `;

  // Log to console to simulate server-side worker dispatch
  console.log('============= DISPATCHING ALERTS =============');
  console.log('📱 TWILIO SMS:');
  console.log(smsPayload);
  console.log('📧 RESEND EMAIL HTML:');
  console.log(emailHtml);
  console.log('==============================================');

  return {
    dispatched: true,
    sms: smsPayload,
    email: emailHtml,
    timestamp: new Date().toISOString()
  };
}
